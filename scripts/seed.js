'use strict';

// Seed script — the ONLY way to create the very first Admin account (there is
// no public sign-up page). Also useful for adding more users from the shell.
//
// Usage:
//   node scripts/seed.js --username admin --password "S3curePass!" --role admin
//   node scripts/seed.js --username jay --name "Jay Sharma" --email jay@cosmicinfosolutions.com \
//        --department Engineering --designation "Senior Engineer" --role employee
//
// Environment variables (equivalent):
//   COSMIC_ADMIN_USERNAME  COSMIC_ADMIN_PASSWORD  COSMIC_ADMIN_ROLE
//   COSMIC_ADMIN_NAME      COSMIC_ADMIN_EMAIL     COSMIC_ADMIN_DEPARTMENT
//   COSMIC_ADMIN_DESIGNATION
//
// Options:
//   --username <name>        default "admin"
//   --password <pass>        if omitted, a strong random password is generated
//   --role <role>            "admin" (default) or "employee"
//   --name <full name>       the employee's Name
//   --email <address>        work e-mail address
//   --department <name>      department
//   --designation <title>    job title
//   --update                 update the account if the username already exists
//
// The account is created in plain JSON storage with a salted scrypt password
// hash — never plain text.

const path = require('path');
const crypto = require('crypto');

const db = require(path.join(__dirname, '..', 'src', 'db'));
const config = require(path.join(__dirname, '..', 'src', 'config'));
const { hashPassword } = require(path.join(__dirname, '..', 'src', 'lib', 'crypto'));
const { isUsername, isPassword, isRole, cleanString, cleanEmail } = require(path.join(__dirname, '..', 'src', 'lib', 'validate'));

function argValue(name) {
  const i = process.argv.indexOf('--' + name);
  if (i === -1 || i + 1 >= process.argv.length || process.argv[i + 1].startsWith('--')) return undefined;
  return process.argv[i + 1];
}

// New COSMIC_* names, with the previous TASKFLOW_* names still honoured so
// existing provisioning scripts keep working.
function env(...names) {
  for (const name of names) {
    if (process.env[name] !== undefined && process.env[name] !== '') return process.env[name];
  }
  return undefined;
}

let username = env('COSMIC_ADMIN_USERNAME', 'TASKFLOW_ADMIN_USERNAME') || argValue('username');
let password = env('COSMIC_ADMIN_PASSWORD', 'TASKFLOW_ADMIN_PASSWORD') || argValue('password');
let role = env('COSMIC_ADMIN_ROLE', 'TASKFLOW_ADMIN_ROLE') || argValue('role');
let name = env('COSMIC_ADMIN_NAME', 'TASKFLOW_ADMIN_NAME') || argValue('name');
let email = env('COSMIC_ADMIN_EMAIL', 'TASKFLOW_ADMIN_EMAIL') || argValue('email');
let department = env('COSMIC_ADMIN_DEPARTMENT') || argValue('department');
let designation = env('COSMIC_ADMIN_DESIGNATION') || argValue('designation');
const force = process.argv.includes('--update') || process.env.COSMIC_FORCE_UPDATE === 'true';

if (!username) username = 'admin';
if (!isRole(role)) role = 'admin';

const autoGenerated = !password;
if (!password) {
  password = crypto.randomBytes(15).toString('base64url'); // 20 strong chars
}

if (!isUsername(username)) {
  console.error('✗ Invalid username "' + username + '". Use 3–32 letters, numbers, ".", "_" or "-".');
  process.exit(1);
}
if (!isPassword(password)) {
  console.error('✗ Password must be between 8 and 128 characters.');
  process.exit(1);
}

if (email) {
  const clean = cleanEmail(email);
  if (!clean) {
    console.error('✗ Invalid e-mail address "' + email + '".');
    process.exit(1);
  }
  email = clean;
}

name = cleanString(name, 80);
department = cleanString(department, 60);
designation = cleanString(designation, 60);

const existing = db.find('users', (u) => String(u.username || '').toLowerCase() === username.toLowerCase());

function optional(value, current) {
  return value ? value : current;
}

if (existing) {
  if (!force) {
    console.log('ℹ User "' + username + '" already exists. Re-run with --update to change its details.');
    process.exit(0);
  }
  const patch = { role };
  if (name) patch.displayName = name;
  if (email !== undefined && email !== '') patch.email = email;
  if (department) patch.department = department;
  if (designation) patch.designation = designation;
  if (!autoGenerated) patch.passwordHash = hashPassword(password);
  patch.updatedAt = db.now();
  db.update('users', existing.id, patch);
  console.log('✓ Updated existing account "' + username + '" (role: ' + role + ').');
  if (!autoGenerated) console.log('  Password updated.');
} else {
  db.insert('users', {
    username,
    displayName: optional(name, username),
    email: email || '',
    department,
    designation,
    role,
    active: true,
    passwordHash: hashPassword(password),
  });
  console.log('✓ ' + config.appName + ' account created.');
  console.log('');
  console.log('  Username   : ' + username);
  console.log('  Name       : ' + optional(name, username));
  console.log('  Email      : ' + (email || '(not set)'));
  console.log('  Department : ' + (department || '(not set)'));
  console.log('  Designation: ' + (designation || '(not set)'));
  console.log('  Role       : ' + role);
  if (autoGenerated) {
    console.log('  Password   : ' + password + '   <-- generated, save it now');
  } else {
    console.log('  Password   : (as provided)');
  }
  console.log('');
  console.log('Sign in at ' + config.publicUrl + '/. You can later add more employees');
  console.log('from the "Manage Users" panel and reset any password there too.');
}

console.log('\nData file: ' + config.dbFile);
